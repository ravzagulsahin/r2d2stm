int same(uchar *uid)
{
  uchar match = 0;

  for (int i = 0; i < UID_ADET; i++)
  {
    uchar eslesti = 1;
    for (int j = 0; j < UID_UZUNLUK; j++)
    {
      if (uid[j] != dogru_uid[i][j])
      {
        eslesti = 0;
        break;
      }
    }
    if (eslesti)
    {
      match = 1;
      break;
    }
  }
  return match;
}
